import { syllableKeys } from "../src/core/zhuyin-keys";

const revision = "5af9da259066dc270c5e5ae76f082636912b75c4";
const upstream = `https://raw.githubusercontent.com/openvanilla/McBopomofo/${revision}/Source/Data/`;
const [occurrences, bases, phrases] = await Promise.all(
  ["phrase.occ", "BPMFBase.txt", "BPMFMappings.txt"].map(async (file) => {
    const response = await fetch(upstream + file, { signal: AbortSignal.timeout(90_000) });
    if (!response.ok) throw new Error(`Could not download ${file}: ${response.status}`);
    return (await response.text()).trim().split(/\r?\n/);
  }),
);
const counts = new Map<string, number>();
for (const line of occurrences ?? []) {
  const [word, count] = line.trim().split(/\s+/);
  if (word && count && Number.isFinite(Number(count))) counts.set(word, Number(count));
}

const rows = new Map<string, number>();
const covered = new Set<string>();
function add(word: string, reading: string[], count: number): boolean {
  if (!/^\p{Unified_Ideograph}+$/u.test(word) || Array.from(word).length !== reading.length) return false;
  const keys = reading.map(syllableKeys);
  if (keys.some((key) => !key)) return false;
  const row = `${keys.join(" ")}|${word}`;
  rows.set(row, Math.max(count, rows.get(row) ?? 0));
  return true;
}
for (const line of bases ?? []) {
  const [character, phonetic] = line.trim().split(/\s+/);
  if (!character || !phonetic) continue;
  const count = counts.get(character) ?? 0;
  const key = syllableKeys(phonetic);
  if (!key || (count < 4 && covered.has(key))) continue;
  if (add(character, [phonetic], Math.max(count, 1))) covered.add(key);
}
const characters = rows.size;
for (const line of phrases ?? []) {
  const [word, ...reading] = line.trim().split(/\s+/);
  if (!word || reading.length < 2 || reading.length > 8) continue;
  const count = counts.get(word) ?? 0;
  if (count >= 12) add(word, reading, count);
}
if (characters < 5000 || rows.size < 25_000) throw new Error("Incomplete upstream dictionary.");
const sorted = [...rows].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const data = sorted.map(([row, count]) => `${row}|${count}`).join("\n");
const notice = `# Generated by scripts/build-zhuyin-dictionary.ts; do not edit.
# Based on McBopomofo (小麥注音), commit ${revision}.
# MIT License, Copyright (c) 2011-2026 Mengjuei Hsieh et al.
# Full notice: public/mcbopomofo-license.txt
${data}\n`;
await Bun.write(new URL("../src/data/mcbopomofo.generated.txt", import.meta.url), notice);
console.log(`Generated ${rows.size} readings (${characters} single-character, ${rows.size - characters} phrase).`);
