import { analyze } from "./analyze";
import { mayNeedZhuyinDictionary } from "./keyboard-recovery";
import type { AnalysisOptions, AnalysisResult } from "./types";
import { installZhuyinDictionary } from "./zhuyin";

let load: Promise<void> | undefined;

export async function analyzeInBrowser(text: string, options: AnalysisOptions): Promise<AnalysisResult> {
  if (mayNeedZhuyinDictionary(text, options.mode)) {
    // A versioned static asset; no user text is included in the request.
    load ??= fetch(new URL("../data/mcbopomofo.generated.txt", import.meta.url), {
      credentials: "omit",
      redirect: "error",
      signal: AbortSignal.timeout(5_000),
    }).then(async (response) => {
      if (!response.ok) return;
      const data = await response.text();
      if (data.startsWith("# Generated by scripts/build-zhuyin-dictionary.ts")) {
        installZhuyinDictionary(data);
      }
    }).catch(() => {
      // The curated dictionary still works when the extended asset is unavailable.
    });
    await load;
  }
  return analyze(text, options);
}
